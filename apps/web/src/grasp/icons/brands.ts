/**
 * A brand's mark in one colour, the text's: every part in `currentColor`, the white inside left
 * out (a hole) and no gradient. Any other drawing comes back as it is.
 */
export const monoMark = (icon: IconData): IconData => {
  const known = monos.get(icon);
  if (known !== undefined) {
    return known;
  }
  const mono = filledMark(
    icon
      .filter(
        ([tag, attrs]) =>
          tag !== "linearGradient" && !String(attrs.key).startsWith("knockout")
      )
      .map(([tag, attrs]) => [tag, { ...attrs, fill: "currentColor" }] as const)
  );
  monos.set(icon, mono);
  return mono;
};
