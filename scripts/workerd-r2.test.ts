/**
 * The on-prem R2 service on plain workerd, through workerd's own R2 client,
 * as core's R2 bindings reach it there (workerd-r2.ts). A small Worker runs
 * each test's steps on its `FILES` and `OTHER` buckets and answers what R2
 * returned, or the error it threw: the calls core makes.
 */
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { DatabaseSync } from "node:sqlite";
import { setTimeout as sleep } from "node:timers/promises";

import { afterEach, describe, expect, it } from "vite-plus/test";
import { z } from "zod";

import { r2Bindings, r2Service, writeR2Service } from "./workerd-r2.ts";
import {
  cleanUp,
  serveOnWorkerd,
  storageDir,
  tempDir,
} from "./workerd-test-server.ts";

/**
 * Runs the steps it's sent and answers each one's result. A body is text,
 * or `size` generated bytes sent as a stream; a large one comes back as its
 * size and SHA-256 rather than its bytes.
 */
const testWorker = `
const generated = (size) => {
  const bytes = new Uint8Array(size);
  for (let i = 0; i < size; i += 1) bytes[i] = (i * 7) % 251;
  return bytes;
};
const hex = (buffer) => [...new Uint8Array(buffer)].map((b) => b.toString(16).padStart(2, "0")).join("");
const sha256 = async (bytes) => hex(await crypto.subtle.digest("SHA-256", bytes));
const streamOf = (bytes) => {
  const piece = 64 * 1024;
  let at = 0;
  return new ReadableStream({
    pull(controller) {
      if (at >= bytes.byteLength) return controller.close();
      controller.enqueue(bytes.slice(at, at + piece));
      at += piece;
    },
  });
};
const described = (object) => object === null ? null : {
  key: object.key,
  size: object.size,
  etag: object.etag,
  uploaded: object.uploaded instanceof Date,
  httpMetadata: object.httpMetadata,
  sha256: object.checksums.sha256 === undefined ? undefined : hex(object.checksums.sha256),
};
const run = async (env, step) => {
  const bucket = env[step.bucket];
  switch (step.op) {
    case "put": {
      let body = step.text;
      const options = { ...step.options };
      if (step.size !== undefined) {
        const bytes = generated(step.size);
        if (options.sha256 === "of-body") options.sha256 = await sha256(bytes);
        body = new FixedLengthStream(step.size);
        streamOf(bytes).pipeTo(body.writable);
        body = body.readable;
      } else if (options.sha256 === "of-body") {
        options.sha256 = await sha256(new TextEncoder().encode(body));
      }
      return described(await bucket.put(step.key, body, options));
    }
    case "get": {
      const options = step.rangeHeader === undefined
        ? step.options
        : { range: new Headers({ range: step.rangeHeader }) };
      const object = await bucket.get(step.key, options);
      if (object === null) return null;
      if (!("body" in object)) return { ...described(object), body: "none" };
      const bytes = new Uint8Array(await object.arrayBuffer());
      return {
        ...described(object),
        body: bytes.byteLength > 1024 ? { size: bytes.byteLength, sha256: await sha256(bytes) } : new TextDecoder().decode(bytes),
      };
    }
    case "head":
      return described(await bucket.head(step.key));
    case "delete":
      await bucket.delete(step.keys ?? (step.manyKeys === undefined ? step.key : Array.from({ length: step.manyKeys }, (_, i) => "k" + i)));
      return "deleted";
    case "list": {
      const listed = await bucket.list(step.options);
      return {
        keys: listed.objects.map(({ key }) => key),
        uploaded: listed.objects.every(({ uploaded }) => uploaded instanceof Date),
        truncated: listed.truncated,
        cursor: listed.truncated ? listed.cursor : undefined,
        delimitedPrefixes: listed.delimitedPrefixes,
      };
    }
    case "getWhileReplaced": {
      // Reads the first piece of the body, replaces the object, then reads
      // the rest: all of it must be the object as it was when got.
      const object = await bucket.get(step.key);
      const reader = object.body.getReader();
      const pieces = [];
      const first = await reader.read();
      pieces.push(first.value);
      await bucket.put(step.key, "replaced");
      for (;;) {
        const { done, value } = await reader.read();
        if (done) break;
        pieces.push(value);
      }
      const bytes = new Uint8Array(await new Blob(pieces).arrayBuffer());
      const now = await bucket.get(step.key);
      return { body: { size: bytes.byteLength, sha256: await sha256(bytes) }, now: await now.text() };
    }
    case "racePuts": {
      // Writers all start before any finishes: each streams its body in
      // pieces, with a pause between them.
      const write = async (_, index) => {
        const body = new FixedLengthStream(step.pieces * step.pieceSize);
        const put = bucket.put(step.key, body.readable, { onlyIf: { etagDoesNotMatch: "*" } });
        const out = body.writable.getWriter();
        for (let piece = 0; piece < step.pieces; piece += 1) {
          await out.write(new Uint8Array(step.pieceSize).fill(index + 1));
          await scheduler.wait(5);
        }
        await out.close();
        return (await put) === null ? [] : [index + 1];
      };
      const won = (await Promise.all(Array.from({ length: step.writers }, write))).flat();
      const stored = new Uint8Array(await (await bucket.get(step.key)).arrayBuffer());
      return { won, storedFills: [...new Set(stored)], storedSize: stored.byteLength };
    }
    case "putStalled": {
      // Sends part of a body and never the rest: the put never ends.
      const body = new FixedLengthStream(step.sent * 2);
      const put = bucket.put(step.key, body.readable);
      const writer = body.writable.getWriter();
      await writer.write(new Uint8Array(step.sent).fill(1));
      return await put;
    }
    case "pageAll": {
      // Lists page by page to the end: each page's keys and prefixes.
      const pages = [];
      let cursor;
      do {
        const listed = await bucket.list({ ...step.options, ...(cursor === undefined ? {} : { cursor }) });
        pages.push([...listed.objects.map(({ key }) => key), ...listed.delimitedPrefixes]);
        cursor = listed.truncated ? listed.cursor : undefined;
      } while (cursor !== undefined && pages.length < 100);
      return pages;
    }
    case "putMany": {
      for (const key of step.keys) await bucket.put(key, key);
      return step.keys.length;
    }
    case "expected":
      return { size: step.size, sha256: await sha256(generated(step.size)) };
  }
  throw new Error("unknown step");
};
export default {
  async fetch(request, env) {
    const results = [];
    for (const step of await request.json()) {
      try {
        results.push({ ok: await run(env, step) });
      } catch (error) {
        results.push({ error: String(error.message) });
      }
    }
    return Response.json(results);
  },
};
`;

/** One call on a bucket. */
type Step = Record<string, unknown> & {
  op:
    | "put"
    | "get"
    | "head"
    | "delete"
    | "list"
    | "expected"
    | "getWhileReplaced"
    | "racePuts"
    | "putStalled"
    | "pageAll"
    | "putMany";
  bucket?: "FILES" | "OTHER";
};

const resultsSchema = z.array(
  z.union([z.object({ ok: z.unknown() }), z.object({ error: z.string() })])
);

type Results = z.infer<typeof resultsSchema>;

/** A workerd serving the R2 service and the test Worker. */
const serve = async (
  storage = storageDir()
): Promise<{
  run: (steps: Step[]) => Promise<Results>;
  /** Sends steps without waiting for their answer. */
  send: (steps: Step[]) => void;
  stop: () => Promise<void>;
  kill: () => Promise<void>;
}> => {
  const out = tempDir();
  writeFileSync(path.join(out, "test.js"), testWorker);
  writeR2Service(out);
  const { url, stop, kill } = await serveOnWorkerd(
    out,
    (address) => `using Workerd = import "/workerd/workerd.capnp";

const config :Workerd.Config = (
  services = [
    (name = "test", worker = (
      modules = [(name = "test.js", esModule = embed "test.js")],
      compatibilityDate = "2026-09-15",
      bindings = [${r2Bindings(["FILES", "OTHER"]).join(", ")}],
    )),
    (name = "storage", disk = (path = "${storage}", writable = true)),
    ${r2Service("storage")},
  ],
  sockets = [(name = "http", address = "${address}", http = (), service = "test")],
);
`
  );
  return {
    run: async (steps) => {
      const response = await fetch(url, {
        method: "POST",
        body: JSON.stringify(steps),
      });
      return resultsSchema.parse(await response.json());
    },
    send: (steps) => {
      // Its answer never comes, or comes after workerd is gone.
      fetch(url, { method: "POST", body: JSON.stringify(steps) }).catch(
        () => {}
      );
    },
    stop,
    kill,
  };
};

/** The chunks one SQLite file of the R2 service holds. */
const chunksIn = (file: string): number => {
  const db = new DatabaseSync(file, { readOnly: true });
  try {
    // Only a bucket's file has the table; workerd keeps others there.
    const hasChunks =
      db
        .prepare(
          "SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = 'chunks'"
        )
        .get() !== undefined;
    return hasChunks
      ? z
          .object({ n: z.number() })
          .parse(db.prepare("SELECT count(*) AS n FROM chunks").get()).n
      : 0;
  } finally {
    db.close();
  }
};

/** The chunks the R2 service's buckets hold, read from their SQLite files. */
const storedChunks = (storage: string): number => {
  const dir = path.join(storage, "R2Store");
  const files = existsSync(dir)
    ? readdirSync(dir).filter((file) => file.endsWith(".sqlite"))
    : [];
  return files
    .map((file) => chunksIn(path.join(dir, file)))
    .reduce((total, n) => total + n, 0);
};

/** Waits until `holds` does, or fails after `attempts` tries. */
const eventually = async (
  holds: () => boolean,
  attempts = 200
): Promise<void> => {
  if (holds()) {
    return;
  }
  if (attempts === 0) {
    throw new Error("it never happened");
  }
  await sleep(25);
  await eventually(holds, attempts - 1);
};

/** Whether a result is an error saying `message`. */
const refused = (result: unknown, message: string): boolean =>
  JSON.stringify(result).includes(message);

/** The ok value of each result, or its error. */
const values = (results: Results): unknown[] =>
  results.map((result) => ("ok" in result ? result.ok : result));

/** A step putting `key` with itself as its text. */
const putItself = (key: string): Step => ({
  op: "put",
  bucket: "FILES",
  key,
  text: key,
});

/** The fields `names` of a result, to compare only those. */
const picked = (value: unknown, names: readonly string[]): unknown =>
  typeof value === "object" && value !== null
    ? Object.fromEntries(
        names.map((name): [string, unknown] => [name, Reflect.get(value, name)])
      )
    : value;

/** A body over three of the service's 1 MiB chunks. */
const largeSize = 2.5 * 1024 * 1024;

/**
 * A body larger than what workerd buffers between the service and its
 * client, so most of it is still unread after the first piece.
 */
const beyondBuffersSize = 40 * 1024 * 1024;

describe("the on-prem R2 service", () => {
  afterEach(cleanUp);

  it("keeps what's put, as text or as a stream over several chunks, and its metadata", async () => {
    const { run } = await serve();
    const [put, got, head, large, largeGot, expected, missing] = values(
      await run([
        {
          op: "put",
          bucket: "FILES",
          key: "trees/a.json",
          text: "{}",
          options: { httpMetadata: { contentType: "application/json" } },
        },
        { op: "get", bucket: "FILES", key: "trees/a.json" },
        { op: "head", bucket: "FILES", key: "trees/a.json" },
        { op: "put", bucket: "FILES", key: "large", size: largeSize },
        { op: "get", bucket: "FILES", key: "large" },
        { op: "expected", size: largeSize },
        { op: "get", bucket: "FILES", key: "missing" },
      ])
    );
    const object = {
      key: "trees/a.json",
      size: 2,
      // MD5 of "{}", R2's etag.
      etag: "99914b932bd37a50b983c5e7c90ae93b",
      uploaded: true,
      httpMetadata: { contentType: "application/json" },
    };
    expect({
      put,
      got,
      head,
      large: picked(large, ["key", "size"]),
      largeGot: picked(largeGot, ["body"]),
      missing,
    }).toStrictEqual({
      put: object,
      got: { ...object, body: "{}" },
      head: object,
      large: { key: "large", size: largeSize },
      largeGot: { body: expected },
      missing: null,
    });
  });

  it("checks a body against its SHA-256, and refuses one that doesn't match", async () => {
    const { run } = await serve();
    const results = values(
      await run([
        {
          op: "put",
          bucket: "FILES",
          key: "upload",
          size: largeSize,
          options: { sha256: "of-body" },
        },
        {
          op: "put",
          bucket: "FILES",
          key: "damaged",
          text: "bytes",
          options: { sha256: "0".repeat(64) },
        },
        { op: "head", bucket: "FILES", key: "damaged" },
        { op: "expected", size: largeSize },
      ])
    );
    const [upload, damaged, head, expected] = results;
    expect({
      upload: picked(upload, ["key", "sha256"]),
      damaged: JSON.stringify(damaged).includes(
        "The sha256 checksum you specified did not match"
      ),
      head,
    }).toStrictEqual({
      upload: {
        key: "upload",
        ...z.object({ sha256: z.string() }).parse(expected),
      },
      damaged: true,
      head: null,
    });
  });

  it("writes only where nothing is yet, given etagDoesNotMatch *", async () => {
    const { run } = await serve();
    const onlyNew = { onlyIf: { etagDoesNotMatch: "*" } };
    const results = values(
      await run([
        {
          op: "put",
          bucket: "FILES",
          key: "stretch",
          text: "first",
          options: onlyNew,
        },
        {
          op: "put",
          bucket: "FILES",
          key: "stretch",
          text: "second",
          options: onlyNew,
        },
        { op: "get", bucket: "FILES", key: "stretch" },
      ])
    );
    const [first, second, got] = results;
    expect([
      picked(first, ["key", "size"]),
      second,
      picked(got, ["body"]),
    ]).toStrictEqual([{ key: "stretch", size: 5 }, null, { body: "first" }]);
  });

  it("replaces an object whole, and reads part of one", async () => {
    const { run } = await serve();
    const results = values(
      await run([
        { op: "put", bucket: "FILES", key: "k", text: "old value" },
        { op: "put", bucket: "FILES", key: "k", text: "new" },
        { op: "get", bucket: "FILES", key: "k" },
        {
          op: "get",
          bucket: "FILES",
          key: "k",
          options: { range: { offset: 1, length: 1 } },
        },
        {
          op: "get",
          bucket: "FILES",
          key: "k",
          options: { range: { suffix: 2 } },
        },
      ])
    );
    const [old, replaced, whole, middle, suffix] = results;
    expect([
      picked(old, ["size"]),
      picked(replaced, ["size"]),
      picked(whole, ["body"]),
      picked(middle, ["body"]),
      picked(suffix, ["body"]),
    ]).toStrictEqual([
      { size: 9 },
      { size: 3 },
      { body: "new" },
      { body: "e" },
      { body: "ew" },
    ]);
  });

  it("finishes a read of an object replaced while it's read, with the object as it was", async () => {
    const { run } = await serve();
    const [, read, expected] = values(
      await run([
        { op: "put", bucket: "FILES", key: "k", size: beyondBuffersSize },
        { op: "getWhileReplaced", bucket: "FILES", key: "k" },
        { op: "expected", size: beyondBuffersSize },
      ])
    );
    expect(read).toStrictEqual({ body: expected, now: "replaced" });
  });

  it("lets exactly one of many concurrent write-once puts in, and keeps its body", async () => {
    const { run } = await serve();
    const writers = 8;
    const pieces = 4;
    const pieceSize = 256 * 1024;
    const [raced] = values(
      await run([
        {
          op: "racePuts",
          bucket: "FILES",
          key: "stretch",
          writers,
          pieces,
          pieceSize,
        },
      ])
    );
    const { won, storedFills, storedSize } = z
      .object({
        won: z.array(z.number()),
        storedFills: z.array(z.number()),
        storedSize: z.number(),
      })
      .parse(raced);
    expect({ winners: won.length, storedFills, storedSize }).toStrictEqual({
      winners: 1,
      storedFills: won,
      storedSize: pieces * pieceSize,
    });
  });

  it("removes what a put cut off by a crash left behind, when it starts again", async () => {
    const storage = storageDir();
    const first = await serve(storage);
    first.send([
      { op: "putStalled", bucket: "FILES", key: "k", sent: 3 * 1024 * 1024 },
    ]);
    // Its first chunks are on disk before workerd dies.
    await eventually(() => storedChunks(storage) > 0);
    await first.kill();
    const leftBehind = storedChunks(storage);

    const second = await serve(storage);
    const [head] = values(
      await second.run([{ op: "head", bucket: "FILES", key: "k" }])
    );
    await second.stop();
    expect({
      leftBehind: leftBehind > 0,
      head,
      after: storedChunks(storage),
    }).toStrictEqual({
      leftBehind: true,
      head: null,
      after: 0,
    });
  });

  it("refuses what R2 refuses: metadata over 2 KiB in bytes, a bad cursor, an empty range, over 1000 keys to delete", async () => {
    const { run } = await serve();
    const results = values(
      await run([
        { op: "put", bucket: "FILES", key: "k", text: "value" },
        {
          op: "put",
          bucket: "FILES",
          key: "meta",
          text: "x",
          // 1100 characters, but 2200 bytes.
          options: { customMetadata: { note: "é".repeat(1100) } },
        },
        { op: "list", bucket: "FILES", options: { cursor: "not a cursor" } },
        { op: "get", bucket: "FILES", key: "k", rangeHeader: "bytes=-0" },
        { op: "delete", bucket: "FILES", manyKeys: 1001 },
        { op: "head", bucket: "FILES", key: "k" },
      ])
    );
    expect({
      metadata: refused(results[1], "metadata headers exceed"),
      cursor: refused(results[2], "cursor is not valid"),
      range: refused(results[3], "range is not satisfiable"),
      delete: refused(results[4], "up to 1000 keys"),
      kept: picked(results[5], ["key"]),
    }).toStrictEqual({
      metadata: true,
      cursor: true,
      range: true,
      delete: true,
      kept: { key: "k" },
    });
  });

  it("pages through keys starting with a byte order mark, to the end", async () => {
    const { run } = await serve();
    const keys = ["\u{FEFF}a", "\u{FEFF}b"];
    const pages = values(
      await run([
        ...keys.map(putItself),
        { op: "pageAll", bucket: "FILES", options: { limit: 1 } },
      ])
    ).at(-1);
    expect(pages).toStrictEqual([["\u{FEFF}a"], ["\u{FEFF}b"]]);
  });

  it("pages through delimited prefixes with many objects under each", async () => {
    const { run } = await serve();
    const days = ["2026-10-01", "2026-10-02", "2026-10-03"];
    const keys = [
      ...days.flatMap((day) =>
        Array.from(
          { length: 50 },
          (_, i) => `kept/${day}/app/${String(i).padStart(3, "0")}`
        )
      ),
      "kept/loose",
    ];
    const results = values(
      await run([
        { op: "putMany", bucket: "FILES", keys },
        {
          op: "pageAll",
          bucket: "FILES",
          options: { prefix: "kept/", delimiter: "/", limit: 1 },
        },
        {
          op: "pageAll",
          bucket: "FILES",
          options: { prefix: "kept/", delimiter: "/", limit: 2 },
        },
      ])
    );
    expect(results.slice(1)).toStrictEqual([
      [
        ["kept/2026-10-01/"],
        ["kept/2026-10-02/"],
        ["kept/2026-10-03/"],
        ["kept/loose"],
      ],
      [
        ["kept/2026-10-01/", "kept/2026-10-02/"],
        ["kept/loose", "kept/2026-10-03/"],
      ],
    ]);
  });

  it("deletes one key or many", async () => {
    const { run } = await serve();
    const results = values(
      await run([
        putItself("a"),
        putItself("b"),
        putItself("c"),
        { op: "delete", bucket: "FILES", key: "a" },
        { op: "delete", bucket: "FILES", keys: ["b", "c", "never-there"] },
        { op: "list", bucket: "FILES", options: {} },
      ])
    );
    expect(results.slice(3)).toStrictEqual([
      "deleted",
      "deleted",
      {
        keys: [],
        uploaded: true,
        truncated: false,
        delimitedPrefixes: [],
      },
    ]);
  });

  it("lists by prefix, a page at a time, and by delimiter", async () => {
    const { run } = await serve();
    const keys = [
      "kept/2026-10-01/app-a/1",
      "kept/2026-10-01/app-b/2",
      "kept/2026-10-02/app-a/3",
      "other/x",
    ];
    const results = await run([
      ...keys.map((key): Step => ({
        op: "put",
        bucket: "FILES",
        key,
        text: key,
      })),
      { op: "list", bucket: "FILES", options: { prefix: "kept/", limit: 2 } },
      {
        op: "list",
        bucket: "FILES",
        options: { prefix: "kept/", delimiter: "/" },
      },
    ]);
    const [firstPage, delimited] = values(results.slice(keys.length));
    const { cursor } = z.object({ cursor: z.string() }).parse(firstPage);
    const [secondPage] = values(
      await run([
        {
          op: "list",
          bucket: "FILES",
          options: { prefix: "kept/", limit: 2, cursor },
        },
      ])
    );
    expect({ firstPage, secondPage, delimited }).toStrictEqual({
      firstPage: {
        keys: keys.slice(0, 2),
        uploaded: true,
        truncated: true,
        cursor,
        delimitedPrefixes: [],
      },
      secondPage: {
        keys: keys.slice(2, 3),
        uploaded: true,
        truncated: false,
        delimitedPrefixes: [],
      },
      delimited: {
        keys: [],
        uploaded: true,
        truncated: false,
        delimitedPrefixes: ["kept/2026-10-01/", "kept/2026-10-02/"],
      },
    });
  });

  it("keeps each bucket apart, and what it holds across restarts", async () => {
    const storage = storageDir();
    const first = await serve(storage);
    await first.run([
      { op: "put", bucket: "FILES", key: "k", size: largeSize },
    ]);
    await first.stop();
    const { run } = await serve(storage);
    const [kept, expected, other] = values(
      await run([
        { op: "get", bucket: "FILES", key: "k" },
        { op: "expected", size: largeSize },
        { op: "get", bucket: "OTHER", key: "k" },
      ])
    );
    expect({ kept: picked(kept, ["body"]), other }).toStrictEqual({
      kept: { body: expected },
      other: null,
    });
  });
});
