/**
 * A stand-in core on plain workerd, for the on-prem sandbox's tests
 * (workerd-sandbox-*.test.ts): a test Worker under apps/core/test/workerd,
 * bundled as core's own deploy bundles, served with `SANDBOX_HOST` bound to
 * the sandbox supervisor's socket, as on-prem binds it.
 */
import { execFileSync } from "node:child_process";
import { readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

import { serveOnWorkerd, tempDir } from "./workerd-test-server.ts";

const repo = path.join(import.meta.dirname, "..");
const core = path.join(repo, "apps/core");

/**
 * Bundles `worker` (a file under apps/core/test/workerd) by Wrangler's dry
 * run into `out`, and answers its capnp module entries for a config there.
 */
const bundle = (out: string, worker: string): string[] => {
  // The compiler's version is generated by its build; no test reads it.
  writeFileSync(
    path.join(out, "version.js"),
    'export const version = "stand-in";'
  );
  const config = path.join(out, "wrangler.jsonc");
  writeFileSync(
    config,
    JSON.stringify({
      name: "stand-in",
      main: path.join(core, "test/workerd", worker),
      compatibility_date: "2026-09-15",
      compatibility_flags: ["nodejs_compat"],
      alias: { "#version": path.join(out, "version.js") },
    })
  );
  const bundled = path.join(out, "bundle");
  execFileSync(
    path.join(repo, "node_modules/.bin/wrangler"),
    ["deploy", "--dry-run", "--outdir", bundled, "--config", config],
    { cwd: core, stdio: "ignore" }
  );
  const main = worker.replace(/\.ts$/u, ".js");
  // Durable Object migrations come along as text modules.
  return [
    `(name = "worker.js", esModule = embed "bundle/${main}")`,
    ...readdirSync(bundled)
      .filter((file) => file.endsWith(".sql"))
      .map((file) => `(name = "${file}", text = embed "bundle/${file}")`),
  ];
};

/** Serves `worker` with `SANDBOX_HOST` at `socket`, and answers its URL. */
export const serveStandIn = async (
  worker: string,
  socket: string,
  bindings: Readonly<Record<string, string>> = {}
): Promise<string> => {
  const out = tempDir();
  const modules = bundle(out, worker);
  const texts = Object.entries(bindings).map(
    ([name, value]) => `(name = "${name}", text = "${value}")`
  );
  const served = await serveOnWorkerd(
    out,
    (address) => `using Workerd = import "/workerd/workerd.capnp";

const config :Workerd.Config = (
  services = [
    (name = "core", worker = .core),
    (name = "sandbox", external = (address = "unix:${socket}", http = ())),
  ],
  sockets = [(name = "http", address = "${address}", http = (), service = "core")],
);

const core :Workerd.Worker = (
  modules = [${modules.join(", ")}],
  compatibilityDate = "2026-09-15",
  compatibilityFlags = ["nodejs_compat"],
  bindings = [
    (name = "RUNTIME_PROFILE", text = "workerd"),
    (name = "SANDBOX_HOST", service = "sandbox"),
    ${texts.join(",\n    ")}
  ],
);
`
  );
  return served.url;
};
