/* oxlint-disable no-template-curly-in-string -- workflow expressions are written as ${ … } strings */
import { spawnSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  realpathSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

import { inspectApp } from "@grasp-os/sdk/host";
import { sdkProtocolVersion } from "@grasp-os/shared/app-releases";
import type { DefinitionPackage } from "@grasp-os/shared/definition-packages";
import { canonicalText } from "@grasp-os/shared/json";
import { afterEach, describe, expect, it, vi } from "vite-plus/test";
import { z } from "zod";

import notes from "../packages/sdk/test/notes/app.ts";
import { packageProject, PackagingError } from "./package-definition-lib.ts";

// Packaging a definition package into a standalone project
// (package-definition-lib.ts). The package is the SDK's Notes fixture, an
// App as the product lays it out, and a workflow generated as a version
// seals it; the project is checked as written, and every refusal leaves
// nothing behind.

const ROOT = path.join(import.meta.dirname, "..");
const notesDir = path.join(ROOT, "packages/sdk/test/notes");
const hash = (digit: string): string => digit.repeat(64);

/** The Notes fixture's source, as an App version's tree holds it. */
const notesFiles = (): Record<string, string> =>
  Object.fromEntries(
    ["app.ts", "schema.ts", "operations/notes.ts"].map((file) => [
      file,
      readFileSync(path.join(notesDir, file), "utf-8"),
    ])
  );

const objectSchema = (properties: Record<string, unknown>) => ({
  format: "json",
  document: {
    type: "object",
    properties,
    required: Object.keys(properties),
    additionalProperties: false,
  },
});

/** A greeting workflow's definition. */
const greetingDefinition = JSON.stringify({
  document: {
    dsl: "1.0.3",
    namespace: "workspace",
    name: "greet",
    version: "1.0.0",
    title: "Greet",
    metadata: {
      grasp: { profile: "grasp-open-workflow/1", params: {}, bindings: {} },
    },
  },
  input: { schema: objectSchema({ who: { type: "string" } }) },
  output: { schema: objectSchema({ status: { type: "string" } }) },
  do: [{ greet: { set: { status: '${ "Hello, " + $workflow.input.who }' } } }],
});

/**
 * The TypeScript a version generates from it, as open-workflow's
 * generator writes it (it needs workerd to check expressions, so it is
 * recorded here).
 */
const greetingSource =
  '// Generated by Grasp from workflow.json: read-only, rebuilt from it.\nimport { openWorkflow } from "@grasp-os/sdk/open-workflow";\nimport type { FlowValue } from "@grasp-os/sdk/open-workflow";\n\nexport default openWorkflow({ profile: "grasp-open-workflow/1" }, async (flow, input) => {\n  let context: FlowValue = {};\n  let output: FlowValue = input;\n  {\n    ({ output, context } = await flow.set("greet", { input: output, context }, { set: async (task) => ({ ["status"]: await task.evaluate(0) }) }));\n  }\n  return output;\n});\n';

/** A greeting workflow's files, as its version seals them. */
const greeting = (): Record<string, string> => ({
  "workflow.json": greetingDefinition,
  ".grasp/workflow.ts": greetingSource,
});

/** A definition package of the Notes App binding the greeting workflow. */
const definitionOf = (
  files: Record<string, string> = notesFiles()
): DefinitionPackage => ({
  formatVersion: 1,
  app: {
    version: 3,
    provenance: {
      manifestHash: hash("a"),
      sourceTreeHash: hash("b"),
      contractHash: hash("c"),
      schemaHash: hash("d"),
      dependencyLockHash: hash("e"),
      sdkVersion: "sdk-1",
      sdkProtocolVersion,
      uiVersion: "ui-1",
      compilerVersion: "compiler-1",
      generated: {},
    },
    files,
    manifest: canonicalText(inspectApp(notes).manifest),
    store: null,
    bindings: {},
    workflows: {},
  },
  workflows: {
    "workspace/greet/1.0.0": {
      provenance: {
        manifestHash: hash("1"),
        definitionHash: hash("2"),
        evaluatorHash: hash("3"),
        buildHash: hash("4"),
        profile: "grasp-open-workflow/1",
      },
      files: greeting(),
      withheldDefaults: [],
      withheldConstraints: [],
      workflows: {},
      bindings: {},
    },
  },
  unresolved: [],
});

/** A locked package, as an App's lock records it. */
const integrity = `sha512-${"A".repeat(86)}==`;
const locked = (
  name: string,
  version: string,
  license: string | null,
  dependencies: Record<string, string> = {}
) => ({
  name,
  version,
  integrity,
  license,
  publishedAt: "2026-01-01T00:00:00.000Z",
  dependencies,
  peers: {},
});
const lockOf = (
  direct: Record<string, string>,
  packages: ReturnType<typeof locked>[]
) =>
  JSON.stringify({
    lockfileVersion: 1,
    registry: "https://registry.npmjs.org",
    requested: Object.fromEntries(
      Object.entries(direct).map(([name, version]) => [name, `^${version}`])
    ),
    direct,
    platformPeers: {},
    targets: {},
    packages: Object.fromEntries(
      packages.map((entry) => [`${entry.name}@${entry.version}`, entry])
    ),
  });

const made: string[] = [];

/** A new empty directory, and where a project would go inside it. */
const scratch = (): { dir: string; out: string } => {
  const dir = mkdtempSync(path.join(tmpdir(), "grasp-package-"));
  made.push(dir);
  return { dir, out: path.join(dir, "project") };
};

const packaged = async (definition: unknown, out: string) =>
  await packageProject({ definition, out, repo: ROOT, commit: "f".repeat(40) });

/** What packaging refused with, or "ok". */
const refusalOf = async (promise: Promise<unknown>): Promise<string> => {
  try {
    await promise;
    return "ok";
  } catch (error) {
    return error instanceof PackagingError ? "refused" : String(error);
  }
};

const packageJsonSchema = z.object({
  dependencies: z.record(z.string(), z.string()),
  devDependencies: z.record(z.string(), z.string()),
});

const exact = /^\d+\.\d+\.\d+$/u;

describe(
  "packaging a definition as a standalone project",
  { timeout: 60_000 },
  () => {
    afterEach(() => {
      for (const dir of made.splice(0)) {
        rmSync(dir, { recursive: true, force: true });
      }
      vi.unstubAllGlobals();
    });

    it("writes the App with its references generated anew, the workflow, the vendored kit and notices, pinned exactly and offline", async () => {
      const fetches = vi.fn<typeof fetch>();
      vi.stubGlobal("fetch", fetches);
      const { out } = scratch();
      const definition = definitionOf();
      const written = await packaged(definition, out);
      const read = (file: string) =>
        readFileSync(path.join(out, file), "utf-8");

      const root = packageJsonSchema.parse(JSON.parse(read("package.json")));
      const vendored = ["sdk", "ui", "shared"].map((name) =>
        packageJsonSchema
          .pick({ dependencies: true })
          .parse(JSON.parse(read(`vendor/@grasp-os/${name}/package.json`)))
      );
      const versions = [
        ...Object.entries(root.dependencies),
        ...Object.entries(root.devDependencies),
        ...vendored.flatMap(({ dependencies }) => Object.entries(dependencies)),
      ].filter(([, version]) => !version.startsWith("file:"));
      const notices = read("THIRD-PARTY-NOTICES.md");

      expect({
        app: written.filter((file) => file.startsWith("app/")),
        workflow: written.filter((file) => file.startsWith("workflows/")),
        vendorTests: written.filter(
          (file) => file.startsWith("vendor/") && /\.test|\/test\//u.test(file)
        ),
        sameSource: read("app/app.ts") === notesFiles()["app.ts"],
        localIdentity:
          read("app/.grasp/references.ts").includes('"local"') &&
          !read("app/.grasp/references.ts").includes("app_0000"),
        grasp: Object.keys(root.dependencies).filter((name) =>
          name.startsWith("@grasp-os/")
        ),
        notExact: versions.filter(([, version]) => !exact.test(version)),
        unnoticed: versions
          .map(([name]) => name)
          .filter((name) => !notices.includes(`| ${name} |`)),
        licence:
          read("LICENSES/AGPL-3.0-only.txt") ===
          readFileSync(path.join(ROOT, "LICENSE"), "utf-8"),
        fetched: fetches.mock.calls.length,
      }).toStrictEqual({
        app: [
          "app/.grasp/contracts.json",
          "app/.grasp/references.ts",
          "app/.grasp/server-references.ts",
          "app/.grasp/server.ts",
          "app/app.ts",
          "app/operations/notes.ts",
          "app/schema.ts",
        ],
        workflow: [
          "workflows/greet/1.0.0/.grasp/workflow.ts",
          "workflows/greet/1.0.0/workflow.json",
        ],
        vendorTests: [],
        sameSource: true,
        localIdentity: true,
        grasp: ["@grasp-os/shared", "@grasp-os/sdk", "@grasp-os/ui"],
        notExact: [],
        unnoticed: [],
        licence: true,
        fetched: 0,
      });
    });

    it("type-checks as written, with its dependencies installed from what the checkout has and no network", async () => {
      const { out } = scratch();
      await packaged(definitionOf(), out);
      // Installed as a package manager would lay them out, from the copies
      // the checkout already holds: nothing is fetched.
      const read = (file: string): Record<string, string> =>
        z
          .object({
            dependencies: z.record(z.string(), z.string()).default({}),
            devDependencies: z.record(z.string(), z.string()).default({}),
          })
          .transform(({ dependencies, devDependencies }) => ({
            ...dependencies,
            ...devDependencies,
          }))
          .parse(JSON.parse(readFileSync(path.join(out, file), "utf-8")));
      const wanted = {
        ...read("vendor/@grasp-os/shared/package.json"),
        ...read("vendor/@grasp-os/sdk/package.json"),
        ...read("vendor/@grasp-os/ui/package.json"),
        ...read("package.json"),
      };
      const installedIn = [
        "packages/ui",
        "packages/sdk",
        "packages/shared",
        ".",
      ].map((dir) => path.join(ROOT, dir, "node_modules"));
      const missing: string[] = [];
      for (const [name, version] of Object.entries(wanted)) {
        const target = path.join(out, "node_modules", name);
        mkdirSync(path.dirname(target), { recursive: true });
        const from = version.startsWith("file:")
          ? path.join(out, version.slice("file:".length))
          : installedIn
              .map((dir) => path.join(dir, name))
              .find((candidate) => existsSync(candidate));
        if (from === undefined) {
          missing.push(name);
        } else {
          symlinkSync(realpathSync(from), target);
        }
      }
      const checked = spawnSync(
        path.join(ROOT, "node_modules/.bin/tsc"),
        ["--noEmit", "-p", "."],
        { cwd: out, encoding: "utf-8" }
      );
      expect({
        missing,
        status: checked.status,
        errors: checked.stdout,
      }).toStrictEqual({
        missing: [],
        status: 0,
        errors: "",
      });
    });

    it("refuses a path that leaves its directory, collides once folded, a tool reads, or a file system can't hold, and writes nothing", async () => {
      const paths = [
        "../escape.ts",
        "operations/../../escape.ts",
        "/etc/passwd",
        "C:/Windows/win.ini",
        "operations\\notes.ts",
        "operations//notes.ts",
        "./app.ts",
        "nul\0.ts",
        "APP.ts",
        "operationſ/notes.ts",
        ".grasp/server.ts",
        "CON.ts",
        "operations/lpt1",
        "notes.ts.",
        "notes.ts ",
        "tab\u0009.ts",
        ".git/config",
        "operations/.GIT/hooks/pre-commit",
        ".npmrc",
        ".vscode/settings.json",
        `${"a".repeat(256)}.ts`,
      ];
      const outcomes: Record<string, string> = {};
      for (const file of paths) {
        const { dir, out } = scratch();
        const definition = definitionOf({
          ...notesFiles(),
          [file]: "export {};\n",
        });
        // oxlint-disable-next-line no-await-in-loop -- one project at a time
        const outcome = await refusalOf(packaged(definition, out));
        outcomes[file] = `${outcome}, ${readdirSync(dir).length} written`;
      }
      expect(outcomes).toStrictEqual(
        Object.fromEntries(paths.map((file) => [file, "refused, 0 written"]))
      );
    });

    it("pins the App's locked packages and their dependencies exactly, and refuses a lock that would replace what the project pins", async () => {
      const withLock = (lock: string) =>
        definitionOf({
          ...notesFiles(),
          "package.json": JSON.stringify({
            dependencies: { "date-kit": "^1.2.0" },
          }),
          "grasp.lock.json": lock,
        });
      const { out } = scratch();
      await packaged(
        withLock(
          lockOf({ "date-kit": "1.2.0" }, [
            locked("date-kit", "1.2.0", "MIT | injected\n| row |", {
              "tz-data": "2.0.1",
            }),
            locked("tz-data", "2.0.1", "Apache-2.0"),
          ])
        ),
        out
      );
      const project = z
        .object({
          dependencies: z.record(z.string(), z.string()),
          overrides: z.record(z.string(), z.record(z.string(), z.string())),
        })
        .parse(
          JSON.parse(readFileSync(path.join(out, "package.json"), "utf-8"))
        );
      const notices = readFileSync(
        path.join(out, "THIRD-PARTY-NOTICES.md"),
        "utf-8"
      );
      const refused = await Promise.all(
        [
          lockOf({ "@grasp-os/sdk": "9.9.9" }, [
            locked("@grasp-os/sdk", "9.9.9", "MIT"),
          ]),
          lockOf({ react: "18.0.0" }, [locked("react", "18.0.0", "MIT")]),
          lockOf({ typescript: "5.0.0" }, [
            locked("typescript", "5.0.0", "MIT"),
          ]),
          lockOf({ "date-kit": "1.2.0" }, [
            locked("date-kit", "1.2.0", "MIT", { "@grasp-os/shared": "1.0.0" }),
            locked("@grasp-os/shared", "1.0.0", "MIT"),
          ]),
        ].map(
          async (lock) =>
            await refusalOf(packaged(withLock(lock), scratch().out))
        )
      );
      expect({
        dateKit: project.dependencies["date-kit"],
        overrides: project.overrides,
        notices: notices
          .split("\n")
          .filter(
            (line) => line.startsWith("| date-kit") || line.includes("injected")
          ),
        refused,
      }).toStrictEqual({
        dateKit: "1.2.0",
        overrides: { "date-kit@1.2.0": { "tz-data": "2.0.1" } },
        notices: ["| date-kit | 1.2.0 | unknown | the App's lock |"],
        refused: ["refused", "refused", "refused", "refused"],
      });
    });

    it("renames the finished project onto an empty --out and leaves nothing beside it", async () => {
      const { dir, out } = scratch();
      mkdirSync(out);
      await packaged(definitionOf(), out);
      expect({
        beside: readdirSync(dir),
        written: readdirSync(out).toSorted(),
      }).toStrictEqual({
        beside: ["project"],
        written: [
          "LICENSES",
          "THIRD-PARTY-NOTICES.md",
          "app",
          "grasp-project.json",
          "package.json",
          "tsconfig.json",
          "vendor",
          "workflows",
        ],
      });
    });

    it("refuses a directory that isn't empty, a package for another protocol, a key that isn't a workflow's, and dependencies with no lock", async () => {
      const used = scratch();
      writeFileSync(path.join(used.dir, "kept.txt"), "kept");
      const definition = definitionOf();
      const { greet } = {
        greet: definition.workflows["workspace/greet/1.0.0"],
      };
      expect({
        nonEmpty: await refusalOf(packaged(definition, used.dir)),
        kept: readFileSync(path.join(used.dir, "kept.txt"), "utf-8"),
        protocol: await refusalOf(
          packaged(
            {
              ...definition,
              app: {
                ...definition.app,
                provenance: {
                  ...definition.app.provenance,
                  sdkProtocolVersion: sdkProtocolVersion + 1,
                },
              },
            },
            scratch().out
          )
        ),
        key: await refusalOf(
          packaged(
            {
              ...definition,
              workflows: { "workspace/../../escape/1.0.0": greet },
            },
            scratch().out
          )
        ),
        unlocked: await refusalOf(
          packaged(
            definitionOf({
              ...notesFiles(),
              "package.json": JSON.stringify({
                dependencies: { "left-pad": "^1.0.0" },
              }),
            }),
            scratch().out
          )
        ),
        notAPackage: await refusalOf(
          packaged({ formatVersion: 1 }, scratch().out)
        ),
      }).toStrictEqual({
        nonEmpty: "refused",
        kept: "kept",
        protocol: "refused",
        key: "refused",
        unlocked: "refused",
        notAPackage: "refused",
      });
    });
  }
);
